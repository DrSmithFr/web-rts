// Command genvec regenerates sim/rng/testdata/pcg32_vectors.txt.
//
// Regeneration is a deliberate act: existing vectors must stay valid forever
// because replays depend on the frozen sequence.
package main

import (
	"bufio"
	"fmt"
	"os"

	"rts/sim/rng"
)

func main() {
	seeds := [][2]uint64{
		{0x853c49e6748fea9b, 0xda3e39cb94b95bdb},
		{0x0000000000000000, 0x0000000000000000},
		{42, 54},
		{1, 0},
		{0xffffffffffffffff, 0xffffffffffffffff},
	}
	f, err := os.Create("sim/rng/testdata/pcg32_vectors.txt")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	w := bufio.NewWriter(f)
	fmt.Fprintln(w, "# PCG32 reference vectors: initState,initSeq,out0,out1,out2,out3,out4 (hex, 32-bit each)")
	fmt.Fprintln(w, "# Generated by tools/genvec from the pcg_basic reference algorithm. Do not regenerate casually.")
	for _, s := range seeds {
		p := rng.Seed(s[0], s[1])
		fmt.Fprintf(w, "%016x,%016x,", s[0], s[1])
		for i := 0; i < 5; i++ {
			if i > 0 {
				fmt.Fprint(w, ",")
			}
			fmt.Fprintf(w, "%08x", p.Next())
		}
		fmt.Fprintln(w)
	}
	if err := w.Flush(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
